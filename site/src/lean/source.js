// Assembling a learner's input into a compilable Lean file.
//
// Two shapes, chosen by the content's declared `kind` (see src/content/index.js):
//
//   'tactic' (default)  the lesson owns statement + context, the learner owns an
//                       indented tactic block inside `:= by`.
//   'file'              the learner owns the whole file; `context` is a fixed
//                       preamble they may rely on.
//
// Nothing here knows anything about a specific lesson: kind, context and
// statement are all declared by the content.

/** Axiom used by the goal-inspection pass: closes any goal so elaboration
 *  succeeds even while goals are open, letting `trace_state` report them. */
export const PREVIEW_AXIOM = 'leanTutorialPreviewClose';

/** Handshake marker for goal traces; must never appear in learner input. */
export const GOAL_TRACE_MARKER = '__LEAN_TUTORIAL_GOAL_9F3A1C__';

/** Identifiers that would make a "proof" not a proof, whatever the lesson. */
const FORBIDDEN = [
  'sorry',
  'admit',
  'sorryAx',
  'native_decide',
  'Lean.ofReduceBool',
  'set_option',
  PREVIEW_AXIOM,
  'browser_preview_close',
];

export const FORBIDDEN_HELP = {
  sorry: '`sorry` accepts the goal without proving it, so it is not a proof.',
  admit: '`admit` (Lean 3 spelling) is not a proof either.',
  sorryAx: '`sorryAx` is the axiom `sorry` hides behind.',
  native_decide: '`native_decide` trusts compiled code; use `decide` (kernel-checked) instead.',
  'Lean.ofReduceBool': '`Lean.ofReduceBool` bypasses the kernel — not allowed here.',
  set_option: 'Options are set by the lesson, not by the answer.',
};

/**
 * Replace comments and string literals with spaces, so policy checks look at
 * code only (`-- sorry` in a comment is fine, `exact sorryAx` is not).
 */
export function codeOnly(source) {
  let out = '';
  let index = 0;
  let blockDepth = 0;
  let inLineComment = false;
  let inString = false;
  while (index < source.length) {
    const char = source[index];
    const next = source[index + 1];
    if (inLineComment) {
      if (char === '\n') { inLineComment = false; out += char; } else out += ' ';
      index += 1;
    } else if (inString) {
      if (char === '\\') { out += '  '; index += 2; continue; }
      if (char === '"') inString = false;
      out += char === '\n' ? char : ' ';
      index += 1;
    } else if (blockDepth > 0) {
      if (char === '/' && next === '-') { blockDepth += 1; out += '  '; index += 2; continue; }
      if (char === '-' && next === '/') { blockDepth -= 1; out += '  '; index += 2; continue; }
      out += char === '\n' ? char : ' ';
      index += 1;
    } else if (char === '-' && next === '-') {
      inLineComment = true; out += '  '; index += 2;
    } else if (char === '/' && next === '-') {
      blockDepth = 1; out += '  '; index += 2;
    } else if (char === '"') {
      inString = true; out += ' '; index += 1;
    } else {
      out += char; index += 1;
    }
  }
  return out;
}

/** Whitespace-insensitive form, for `require` checks. */
const flatten = (text) => codeOnly(String(text)).replace(/\s+/g, '');

const identifierPattern = (word) =>
  new RegExp(`(^|[^A-Za-z0-9_'.])${word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}([^A-Za-z0-9_']|$)`);

/** @returns {{word: string, help: string}[]} forbidden identifiers actually used */
export function forbiddenUsed(input, extra = []) {
  const code = codeOnly(input);
  return [...FORBIDDEN, ...extra]
    .filter((word) => identifierPattern(word).test(code))
    .map((word) => ({ word, help: FORBIDDEN_HELP[word] ?? `\`${word}\` is not allowed in an answer here.` }));
}

/** @returns {string[]} `require` rules the input does not satisfy */
export function missingRequirements(input, require = []) {
  const flat = flatten(input);
  return require.filter((needle) => !flat.includes(String(needle).replace(/\s+/g, '')));
}

function splitLines(text) {
  const lines = String(text ?? '').replace(/\r\n?/g, '\n').split('\n');
  while (lines.length > 0 && lines[lines.length - 1].trim() === '') lines.pop();
  return lines;
}

function header(lesson, extra = []) {
  return [
    '-- generated by lean-tutorials; only the learner’s lines are checked against the editor',
    'set_option autoImplicit false',
    ...(lesson.context ? ['', lesson.context.trimEnd()] : []),
    ...extra,
  ];
}

/**
 * @param {{kind?: string, statement?: string, context?: string}} lesson
 * @param {string} input learner input
 * @param {{preview?: boolean}} [options] preview adds the goal-tracing wrapper
 */
export function buildSource(lesson, input, options = {}) {
  const kind = lesson.kind ?? 'tactic';
  const userLines = splitLines(input);
  const empty = codeOnly(userLines.join('\n')).trim() === '';

  if (kind === 'file') {
    const lines = header(lesson);
    lines.push('', '-- your file');
    const userStartLine = lines.length + 1;
    for (const line of userLines) lines.push(line);
    return {
      code: `${lines.join('\n')}\n`,
      userStartLine,
      userLineCount: userLines.length,
      wrapperStartLine: userStartLine + userLines.length,
      empty,
    };
  }

  const preview = Boolean(options.preview);
  const lines = header(lesson, preview ? ['', `private axiom ${PREVIEW_AXIOM} {α : Sort _} : α`] : []);
  lines.push('', `${String(lesson.statement ?? '').trim()} := by`);

  const userStartLine = lines.length + 1;
  for (const line of userLines) lines.push(line.trim() === '' ? '' : `  ${line}`);
  const wrapperStartLine = userStartLine + userLines.length;

  if (preview) {
    lines.push(
      '  all_goals',
      `    trace "${GOAL_TRACE_MARKER}"`,
      '    trace_state',
      `  all_goals exact ${PREVIEW_AXIOM}`,
    );
  }

  return {
    code: `${lines.join('\n')}\n`,
    userStartLine,
    userLineCount: userLines.length,
    wrapperStartLine: preview ? wrapperStartLine : userStartLine + userLines.length,
    empty,
  };
}

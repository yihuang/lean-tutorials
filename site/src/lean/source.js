// Assembling a lesson into a compilable Lean file.
//
// A lesson owns the prelude (context + statement) and the learner owns one
// indented tactic block, so a "proof" can never redefine the thing it is meant
// to prove. Because the block lands inside `:= by`, the whole file is still a
// single kernel-checked declaration.

/** Axiom used by the goal-inspection pass: closes any goal so elaboration
 *  succeeds even while goals are open, letting `trace_state` report them. */
export const PREVIEW_AXIOM = 'leanTutorialPreviewClose';

/** Handshake marker for goal traces; must never appear in learner input. */
export const GOAL_TRACE_MARKER = '__LEAN_TUTORIAL_GOAL_9F3A1C__';

/** Tactics/identifiers that would make a "proof" not a proof. */
const FORBIDDEN = [
  'sorry',
  'admit',
  'sorryAx',
  'native_decide',
  'Lean.ofReduceBool',
  'set_option',
  PREVIEW_AXIOM,
  'browser_preview_close',
];

export const FORBIDDEN_HELP = {
  sorry: '`sorry` accepts the goal without proving it, so it is not a proof.',
  admit: '`admit` (Lean 3 spelling) is not a proof either.',
  sorryAx: '`sorryAx` is the axiom `sorry` hides behind.',
  native_decide: '`native_decide` trusts compiled code; use `decide` (kernel-checked) instead.',
  'Lean.ofReduceBool': '`Lean.ofReduceBool` bypasses the kernel — not allowed here.',
  set_option: 'Options are set by the lesson, not inside a proof.',
};

/**
 * Replace comments and string literals with spaces, so policy checks look at
 * code only (`-- sorry` in a comment is fine, `exact sorryAx` is not).
 */
export function codeOnly(source) {
  let out = '';
  let index = 0;
  let blockDepth = 0;
  let inLineComment = false;
  let inString = false;
  while (index < source.length) {
    const char = source[index];
    const next = source[index + 1];
    if (inLineComment) {
      if (char === '\n') { inLineComment = false; out += char; } else out += ' ';
      index += 1;
    } else if (inString) {
      if (char === '\\') { out += '  '; index += 2; continue; }
      if (char === '"') inString = false;
      out += char === '\n' ? char : ' ';
      index += 1;
    } else if (blockDepth > 0) {
      if (char === '/' && next === '-') { blockDepth += 1; out += '  '; index += 2; continue; }
      if (char === '-' && next === '/') { blockDepth -= 1; out += '  '; index += 2; continue; }
      out += char === '\n' ? char : ' ';
      index += 1;
    } else if (char === '-' && next === '-') {
      inLineComment = true; out += '  '; index += 2;
    } else if (char === '/' && next === '-') {
      blockDepth = 1; out += '  '; index += 2;
    } else if (char === '"') {
      inString = true; out += ' '; index += 1;
    } else {
      out += char; index += 1;
    }
  }
  return out;
}

/** @returns {string[]} forbidden identifiers the learner actually used */
export function forbiddenUsed(tactics) {
  const code = codeOnly(tactics);
  return FORBIDDEN.filter((word) => new RegExp(`(^|[^A-Za-z0-9_'.])${word}([^A-Za-z0-9_']|$)`).test(code));
}

function splitTactics(tactics) {
  const lines = String(tactics ?? '').replace(/\r\n?/g, '\n').split('\n');
  while (lines.length > 0 && lines[lines.length - 1].trim() === '') lines.pop();
  return lines;
}

/**
 * Build the file to compile.
 *
 * @param {{context?: string, statement: string}} lesson
 * @param {string} tactics learner input (one tactic per line, unindented)
 * @param {{preview?: boolean}} [options] preview adds the goal-tracing wrapper
 */
export function buildSource(lesson, tactics, options = {}) {
  const preview = Boolean(options.preview);
  const userLines = splitTactics(tactics);
  const lines = [
    '-- generated by lean-tutorials: the learner only supplies the tactic block',
    'set_option autoImplicit false',
  ];
  if (lesson.context) {
    lines.push('', lesson.context.trimEnd());
  }
  if (preview) {
    lines.push('', `private axiom ${PREVIEW_AXIOM} {α : Sort _} : α`);
  }
  lines.push('', `${lesson.statement.trim()} := by`);

  const userStartLine = lines.length + 1;
  for (const line of userLines) lines.push(line.trim() === '' ? '' : `  ${line}`);
  const userLineCount = userLines.length;
  const wrapperStartLine = userStartLine + userLineCount;

  if (preview) {
    lines.push(
      '  all_goals',
      `    trace "${GOAL_TRACE_MARKER}"`,
      '    trace_state',
      `  all_goals exact ${PREVIEW_AXIOM}`,
    );
  }

  return {
    code: `${lines.join('\n')}\n`,
    userStartLine,
    userLineCount,
    wrapperStartLine: preview ? wrapperStartLine : userStartLine + userLineCount,
    // "nothing real here" — comments and blank lines do not count as an attempt.
    empty: codeOnly(userLines.join('\n')).trim() === '',
  };
}
